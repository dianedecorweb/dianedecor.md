const isEmpty = (value) => (Array.isArray(value) ? value.length === 0 : !value?.trim())

/** Scrie doar câmpurile rusești goale (sau toate, cu --force). Întoarce câte a scris. */
async function fill(model, rows, keyField, translations) {
  let written = 0
  for (const row of rows) {
    const translation = translations[row[keyField]]
    if (!translation) continue
    const data = Object.fromEntries(
      Object.entries(translation).filter(([field]) => FORCE || isEmpty(row[field]))
    )
    if (Object.keys(data).length === 0) continue
    await model.update({ where: { id: row.id }, data })
    written += 1
  }
  return written
}

